def extract_rows(obj: Any) -> list[dict[str, Any]]:
    if isinstance(obj, list):
        return [r for r in obj if isinstance(r, dict)]
    if isinstance(obj, dict):
        for key in ["data", "series", "history", "prices"]:
            if isinstance(obj.get(key), list):
                return [r for r in obj[key] if isinstance(r, dict)]
        # Date-keyed dict.
        rows = []
        for d, v in obj.items():
            if isinstance(d, str) and len(d) >= 10 and d[4] == "-":
                if isinstance(v, dict):
                    r = dict(v)
                    r.setdefault("date", d[:10])
                    rows.append(r)
                elif isinstance(v, (int, float)):
                    rows.append({"date": d[:10], "close": float(v)})
        if rows:
            rows.sort(key=lambda r: str(r.get("date")))
            return rows
        # Columnar dict fallback.
        dates = obj.get("dates") or obj.get("date") or obj.get("Date")
        closes = obj.get("close") or obj.get("closes") or obj.get("prices") or obj.get("Close") or obj.get("adj_close") or obj.get("Adj Close")
        vols = obj.get("volume") or obj.get("volumes") or obj.get("Volume")
        highs = obj.get("high") or obj.get("High")
        lows = obj.get("low") or obj.get("Low")
        if isinstance(dates, list) and isinstance(closes, list):
            out = []
            for i, d in enumerate(dates):
                if i >= len(closes):
                    break
                r = {"date": str(d)[:10], "close": closes[i]}
                if isinstance(vols, list) and i < len(vols):
                    r["volume"] = vols[i]
                if isinstance(highs, list) and i < len(highs):
                    r["high"] = highs[i]
                if isinstance(lows, list) and i < len(lows):
                    r["low"] = lows[i]
                out.append(r)
            return out
    return []


def get_field(row: dict[str, Any], names: list[str]) -> float | None:
    for name in names:
        if name in row and row[name] is not None:
            try:
                y = float(row[name])
                if math.isfinite(y):
                    return y
            except Exception:
                pass
    return None


def price_file_candidates(symbol: str) -> list[Path]:
    safe = symbol.replace("/", "-")
    return [
        PRICES_DIR / f"{symbol}.json",
        PRICES_DIR / f"{safe}.json",
        PRICES_DIR / f"{symbol.replace('^','')}.json",
        PRICES_DIR / f"{symbol.replace('^','_')}.json",
    ]


def load_records(symbol: str) -> dict[str, list[Any]]:
    for path in price_file_candidates(symbol):
        if not path.exists():
            continue
        try:
            rows = extract_rows(load_json(path))
        except Exception:
            continue
        dates, close, volume, high, low = [], [], [], [], []
        for r in rows:
            d = r.get("date") or r.get("Date")
            c = get_field(r, ["close", "Close", "adj_close", "Adj Close"])
            if d is None or c is None:
                continue
            dates.append(str(d)[:10])
            close.append(c)
            volume.append(get_field(r, ["volume", "Volume", "vol"]))
            high.append(get_field(r, ["high", "High"]))
            low.append(get_field(r, ["low", "Low"]))
        if len(dates) >= 90:
            return {"dates": dates, "close": close, "volume": volume, "high": high, "low": low}
    return {"dates": [], "close": [], "volume": [], "high": [], "low": []}


def load_all_records(symbols: list[str]) -> dict[str, dict[str, list[Any]]]:
    out = {}
    for sym in symbols:
        rec = load_records(sym)
        if rec["dates"]:
            out[sym] = rec
    return out


def pct_return(a: float | None, b: float | None) -> float | None:
    if a is None or b is None or a <= 0 or b <= 0:
        return None
    return (b / a - 1.0) * 100.0


def slice_vals(vals: list[Any], start: int, end: int) -> list[float]:
    out = []
    for v in vals[max(0, start): end]:
        if isinstance(v, (int, float)) and math.isfinite(float(v)):
            out.append(float(v))
    return out


def sum_vals(vals: list[Any]) -> float | None:
    xs = [float(v) for v in vals if isinstance(v, (int, float)) and math.isfinite(float(v))]
    return sum(xs) if xs else None


def returns_std(closes: list[float], start: int, end: int) -> float | None:
    rets = []
    s = max(1, start)
    for i in range(s, end):
        if i < len(closes) and closes[i - 1] > 0 and closes[i] > 0:
            rets.append(closes[i] / closes[i - 1] - 1.0)
    if len(rets) < 3:
        return None
    return statistics.pstdev(rets)


def true_ranges(rec: dict[str, list[Any]], start: int, end: int) -> list[float]:
    closes = rec["close"]
    highs = rec.get("high", [])
    lows = rec.get("low", [])
    out = []
    for i in range(max(1, start), min(end, len(closes))):
        h = highs[i] if i < len(highs) else None
        l = lows[i] if i < len(lows) else None
        pc = closes[i - 1]
        if h is None or l is None or pc is None:
            continue
        try:
            out.append(max(float(h) - float(l), abs(float(h) - float(pc)), abs(float(l) - float(pc))))
        except Exception:
            continue
    return out


def flow_metrics(row: dict[str, Any], records_map: dict[str, dict[str, list[Any]]], spx_rec: dict[str, list[Any]]) -> dict[str, Any]:
    sym = row.get("symbol")
    d = row.get("date")
    rec = records_map.get(sym or "")
    if not rec or not d:
        return {"has_volume_data": False}
    dates = rec["dates"]
    idx = {x: i for i, x in enumerate(dates)}
    i = idx.get(str(d))
    if i is None or i < 60:
        return {"has_volume_data": False}

    closes = rec["close"]
    vols = rec.get("volume", [])
    if not vols or i >= len(vols) or vols[i] is None:
        return {"has_volume_data": False}

    avg_vol_5 = avg(slice_vals(vols, i - 4, i + 1))
    avg_vol_10 = avg(slice_vals(vols, i - 9, i + 1))
    avg_vol_20 = avg(slice_vals(vols, i - 19, i + 1))
    avg_vol_50 = avg(slice_vals(vols, i - 49, i + 1))

    rvol_5_20 = avg_vol_5 / avg_vol_20 if avg_vol_5 and avg_vol_20 and avg_vol_20 > 0 else None
    rvol_10_50 = avg_vol_10 / avg_vol_50 if avg_vol_10 and avg_vol_50 and avg_vol_50 > 0 else None

    def up_volume_ratio(n: int) -> float | None:
        total = 0.0
        up = 0.0
        for k in range(max(1, i - n + 1), i + 1):
            v = vols[k] if k < len(vols) else None
            if not isinstance(v, (int, float)) or not math.isfinite(float(v)):
                continue
            total += float(v)
            if closes[k] > closes[k - 1]:
                up += float(v)
        return up / total * 100.0 if total > 0 else None

    upvol_10 = up_volume_ratio(10)
    upvol_20 = up_volume_ratio(20)

    dollar_vals = []
    for k in range(max(0, i - 19), i + 1):
        if k < len(vols) and vols[k] is not None and closes[k] is not None:
            try:
                dollar_vals.append(float(vols[k]) * float(closes[k]))
            except Exception:
                pass
    dollar_vol_20_m = statistics.mean(dollar_vals) / 1_000_000.0 if dollar_vals else None

    stock_20 = pct_return(closes[i - 20] if i >= 20 else None, closes[i])
    spx_idx = {x: j for j, x in enumerate(spx_rec["dates"])}
    si = spx_idx.get(str(d))
    spx_20 = pct_return(spx_rec["close"][si - 20], spx_rec["close"][si]) if si is not None and si >= 20 else None
    rel_20 = stock_20 - spx_20 if stock_20 is not None and spx_20 is not None else None

    # Setup quality: dry-up and volatility compression are useful before a break/confirmation.
    volume_dryup_5_20 = avg_vol_5 / avg_vol_20 if avg_vol_5 and avg_vol_20 and avg_vol_20 > 0 else None
    trs5 = true_ranges(rec, i - 4, i + 1)
    trs20 = true_ranges(rec, i - 19, i + 1)
    atr_comp = None
    if trs5 and trs20 and statistics.mean(trs20) > 0:
        atr_comp = statistics.mean(trs5) / statistics.mean(trs20)
    else:
        std5 = returns_std(closes, i - 4, i + 1)
        std20 = returns_std(closes, i - 19, i + 1)
        if std5 is not None and std20 and std20 > 0:
            atr_comp = std5 / std20

    hi252 = max(closes[max(0, i - 251): i + 1]) if i >= 20 else None
    dist_52w_high_pct = (closes[i] / hi252 - 1.0) * 100.0 if hi252 and hi252 > 0 else None

    # 100-point market-flow score. Research prior only.
    score = 0.0
    # Relative volume / participation, 25 pts.
    score += min(15.0, max(0.0, (num(rvol_5_20) - 0.9) / 0.5 * 15.0))
    score += min(10.0, max(0.0, (num(rvol_10_50) - 0.9) / 0.4 * 10.0))
    # Up-day volume confirmation, 25 pts.
    score += min(13.0, max(0.0, (num(upvol_10) - 45.0) / 20.0 * 13.0))
    score += min(12.0, max(0.0, (num(upvol_20) - 45.0) / 20.0 * 12.0))
    # Liquidity / real money participation, 15 pts.
    adv = num(dollar_vol_20_m)
    if adv >= 500:
        score += 15.0
    elif adv >= 250:
        score += 12.0
    elif adv >= 100:
        score += 9.0
    elif adv >= 50:
        score += 5.0
    # Price-volume confirmation, 15 pts.
    if stock_20 is not None and stock_20 > 0:
        score += 5.0
    if rel_20 is not None and rel_20 > 0:
        score += 5.0
    if upvol_10 is not None and upvol_10 >= 55:
        score += 5.0
    # Setup quality, 20 pts: dry-up before expansion, volatility compression, high proximity.
    if volume_dryup_5_20 is not None:
        score += min(7.0, max(0.0, (1.05 - volume_dryup_5_20) / 0.35 * 7.0))
    if atr_comp is not None:
        score += min(7.0, max(0.0, (1.05 - atr_comp) / 0.35 * 7.0))
    if dist_52w_high_pct is not None:
        score += min(6.0, max(0.0, (20.0 + dist_52w_high_pct) / 20.0 * 6.0))  # full near high, zero if >20% below high

    out = {
        "has_volume_data": True,
        "avg_volume_5d": round_or_none(avg_vol_5, 3),
        "avg_volume_20d": round_or_none(avg_vol_20, 3),
        "avg_volume_50d": round_or_none(avg_vol_50, 3),
        "rvol_5_20": round_or_none(rvol_5_20, 4),
        "rvol_10_50": round_or_none(rvol_10_50, 4),
        "up_volume_ratio_10d_pct": round_or_none(upvol_10, 3),
        "up_volume_ratio_20d_pct": round_or_none(upvol_20, 3),
        "avg_dollar_volume_20d_m": round_or_none(dollar_vol_20_m, 3),
        "stock_return_20d_pct": round_or_none(stock_20, 3),
        "spx_return_20d_pct": round_or_none(spx_20, 3),
        "relative_return_20d_vs_spx_pct": round_or_none(rel_20, 3),
        "volume_dryup_5_20": round_or_none(volume_dryup_5_20, 4),
        "volatility_compression_5_20": round_or_none(atr_comp, 4),
        "distance_to_52w_high_pct": round_or_none(dist_52w_high_pct, 3),
        "market_flow_score": round(score, 3),
        "flow_flags": {
            "relative_volume_confirmed": bool((rvol_5_20 is not None and rvol_5_20 >= 1.2) or (rvol_10_50 is not None and rvol_10_50 >= 1.1)),
            "up_volume_confirmed": bool((upvol_10 is not None and upvol_10 >= 55) and (upvol_20 is not None and upvol_20 >= 52)),
            "liquid_100m_confirmed": bool(dollar_vol_20_m is not None and dollar_vol_20_m >= 100),
            "price_volume_confirmed": bool(stock_20 is not None and stock_20 > 0 and rel_20 is not None and rel_20 > 0 and upvol_10 is not None and upvol_10 >= 55),
            "setup_compression_confirmed": bool((volume_dryup_5_20 is not None and volume_dryup_5_20 <= 0.85) or (atr_comp is not None and atr_comp <= 0.85)),
            "near_52w_high_confirmed": bool(dist_52w_high_pct is not None and dist_52w_high_pct >= -15),
        },
    }
    return out


def attach_flow(rows: list[dict[str, Any]], records_map: dict[str, dict[str, list[Any]]], spx_rec: dict[str, list[Any]]) -> list[dict[str, Any]]:
    out = []
    for r in rows:
        m = flow_metrics(r, records_map, spx_rec)
        rr = dict(r)
        rr.update(m)
        out.append(rr)
    return out


def pass_flow_rule(row: dict[str, Any], rule: str) -> bool:
    flags = row.get("flow_flags") or {}
    if not row.get("has_volume_data"):
        return False
    if rule == "STC_ONLY_WITH_VOLUME_DATA":
        return True
    if rule == "STC_PLUS_RELATIVE_VOLUME":
        return bool(flags.get("relative_volume_confirmed"))
    if rule == "STC_PLUS_UP_VOLUME":
        return bool(flags.get("up_volume_confirmed"))
    if rule == "STC_PLUS_DOLLAR_VOLUME_100M":
        return bool(flags.get("liquid_100m_confirmed"))
    if rule == "STC_PLUS_RVOL_AND_UPVOL":
        return bool(flags.get("relative_volume_confirmed") and flags.get("up_volume_confirmed"))
    if rule == "STC_PLUS_PRICE_VOLUME":
        return bool(flags.get("price_volume_confirmed"))
    if rule == "STC_PLUS_FLOW_SCORE_60":
        return num(row.get("market_flow_score")) >= 60
    if rule == "STC_PLUS_FLOW_SCORE_70":
        return num(row.get("market_flow_score")) >= 70
    if rule == "STC_PLUS_FLOW_SCORE_60_AND_LIQUID":
        return num(row.get("market_flow_score")) >= 60 and bool(flags.get("liquid_100m_confirmed"))
    return False


def top1_by_date_flow(rows: list[dict[str, Any]]) -> list[dict[str, Any]]:
    by_date: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for r in rows:
        by_date[r["date"]].append(r)
    out = []
    for d, group in sorted(by_date.items()):
        out.append(sorted(
            group,
            # Keep Phase 3H baseline comparable with Phase 3G STC screen:
            # select daily Top1 by STC quality first; market-flow is used as a filter/tie-breaker,
            # not as the primary ranking key in this diagnostic.
            key=lambda x: (-num(x.get("stc_score")), int(x.get("leader_rank") or 9999), -num(x.get("leader_score")), -num(x.get("market_flow_score")), str(x.get("symbol") or "")),
        )[0])
    return out


def summarize_rule(rule_rows: list[dict[str, Any]], phase3g, price_map: dict[str, tuple[list[str], list[float]]], spx_dates: list[str], spx_closes: list[float]) -> dict[str, Any]:
    daily_top1 = top1_by_date_flow(rule_rows)
    enriched_all = phase3g.enrich_forward(rule_rows, price_map, spx_dates, spx_closes)
    enriched_top1 = phase3g.enrich_forward(daily_top1, price_map, spx_dates, spx_closes)
    dedup_all = phase3g.dedup_by_symbol_gap(enriched_all, spx_dates, DEDUP_GAP_DAYS)
    dedup_top1 = phase3g.dedup_by_symbol_gap(enriched_top1, spx_dates, DEDUP_GAP_DAYS)
    return {
        "raw_candidates": len(rule_rows),
        "candidate_days": len({r.get("date") for r in rule_rows}),
        "daily_top1_count": len(daily_top1),
        "dedup_all_count": len(dedup_all),
        "dedup_top1_count": len(dedup_top1),
        "forward_all_dedup": phase3g.summarize_forward(dedup_all),
        "forward_daily_top1_dedup": phase3g.summarize_forward(dedup_top1),
        "concentration_top1_dedup": phase3g.concentration(dedup_top1),
        "avg_market_flow_score_top1": round_or_none(avg([num(r.get("market_flow_score")) for r in dedup_top1]), 3),
        "sample_top1": dedup_top1[:10],
    }


def base_stc_candidates(phase3g, builder, spx_dates: list[str], regime_daily: dict[str, Any]) -> tuple[list[dict[str, Any]], dict[str, Any]]:
    by_rule, diag = phase3g.screen_stc_candidates(builder, spx_dates, regime_daily)
    rows = []
    for rule in TARGET_BASE_RULES:
        for r in by_rule.get(rule, []):
            rr = dict(r)
            rr["base_stc_rule"] = rule
            rows.append(rr)
    return rows, diag


def decision_from_flow(rule_results: dict[str, Any]) -> dict[str, Any]:
    base = rule_results.get("STC_ONLY_WITH_VOLUME_DATA", {}).get("forward_daily_top1_dedup", {})
    base20 = (base.get("20d") or {}).get("avg_excess_pct")
    base30 = (base.get("30d") or {}).get("avg_excess_pct")
    best_rule = None
    best_score = -999.0
    for rule, rr in rule_results.items():
        if rule == "STC_ONLY_WITH_VOLUME_DATA":
            continue
        f20 = rr.get("forward_daily_top1_dedup", {}).get("20d", {})
        f30 = rr.get("forward_daily_top1_dedup", {}).get("30d", {})
        n = f20.get("n") or 0
        ex20 = f20.get("avg_excess_pct")
        ex30 = f30.get("avg_excess_pct")
        wr20 = f20.get("excess_win_rate_pct") or 0
        if n >= 10 and ex20 is not None and ex30 is not None:
            score = ex20 + ex30 + max(0, wr20 - 50) / 10
            if score > best_score:
                best_score = score
                best_rule = rule
    if best_rule:
        rr = rule_results[best_rule]
        f20 = rr["forward_daily_top1_dedup"]["20d"]
        f30 = rr["forward_daily_top1_dedup"]["30d"]
        n = f20.get("n") or 0
        ex20 = f20.get("avg_excess_pct")
        ex30 = f30.get("avg_excess_pct")
        wr20 = f20.get("excess_win_rate_pct") or 0
        improved = (base20 is None or (ex20 is not None and ex20 > base20)) and (base30 is None or (ex30 is not None and ex30 > base30))
        if n >= 20 and ex20 is not None and ex30 is not None and ex20 > 0 and ex30 > 0 and wr20 >= 50 and improved:
            return {
                "decision": "MARKET_FLOW_CONFIRMATION_PROMISING_DIAGNOSTIC_ONLY",
                "best_rule": best_rule,
                "reason": "Flow confirmation produced positive 20D/30D excess, adequate sample, and improvement over STC-only. Still diagnostic only; execution requires separate portfolio simulation.",
            }
        if n >= 10 and improved and ex20 is not None and ex20 > 0:
            return {
                "decision": "MARKET_FLOW_CONFIRMATION_OBSERVATIONAL_ONLY",
                "best_rule": best_rule,
                "reason": "Flow confirmation improved some metrics but does not meet full execution-evidence thresholds.",
            }
    return {
        "decision": "MARKET_FLOW_WATCHLIST_ONLY_FOR_NOW",
        "best_rule": best_rule,
        "reason": "Market-flow filters did not provide sufficient positive 20D/30D excess evidence versus SPX. Keep SIDEWAYS/DOWNTREND candidates as Watchlist/radar only.",
    }


