def load_phase3g_module():
    if not PHASE3G_SCRIPT.exists():
        raise FileNotFoundError(f"Missing required script: {PHASE3G_SCRIPT}")
    spec = importlib.util.spec_from_file_location("phase3g", PHASE3G_SCRIPT)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"Cannot import {PHASE3G_SCRIPT}")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def load_json(path: Path) -> Any:
    if not path.exists():
        raise FileNotFoundError(f"Missing required input: {path}")
    with path.open("r", encoding="utf-8") as f:
        return json.load(f)


def pct_str(x: Any) -> str:
    try:
        if x is None:
            return "n/a"
        y = float(x)
        if not math.isfinite(y):
            return "n/a"
        return f"{y:+.2f}%"
    except Exception:
        return "n/a"


def round_or_none(x: Any, nd: int = 3) -> Any:
    try:
        if x is None:
            return None
        y = float(x)
        return round(y, nd) if math.isfinite(y) else None
    except Exception:
        return None


def num(x: Any, default: float = 0.0) -> float:
    try:
        if x is None:
            return default
        y = float(x)
        return y if math.isfinite(y) else default
    except Exception:
        return default


def avg(xs: list[float]) -> float | None:
    vals = [float(x) for x in xs if isinstance(x, (int, float)) and math.isfinite(float(x))]
    return statistics.mean(vals) if vals else None


